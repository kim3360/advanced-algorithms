# 거스름돈 문제
# 거스름돈을 최소한의 동전으로 거슬러주는 프로그램
# 동전 종류는 500원, 100원, 50원, 10원
# 거스름돈은 10의 배수로 주어짐
# 거스름돈을 최소한의 동전으로 거슬러주는 프로그램
# 동전 종류는 500원, 100원, 50원, 10원
# 거스름돈은 10의 배수로 주어짐
def main():

    n = int(input()) # 거스름돈 입력
    count = 0 # 동전 개수 초기화
    coin_types = [500, 100, 50, 10] # 동전 종류
    for coin in coin_types:
        count += n // coin # 동전 개수 계산
        n %= coin # 거스름돈 계산
    print(count) # 동전 개수 출력
    return count # 동전 개수 반환
if __name__ == "__main__":
    main()
